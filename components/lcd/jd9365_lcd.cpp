void jd9365_lcd::fillScreen(uint16_t color)
{
    uint16_t width = LCD_H_RES;  // 800
    uint16_t height = LCD_V_RES; // 1280

    size_t line_buffer_size = width * sizeof(uint16_t);
    uint16_t *line_buffer = (uint16_t *)heap_caps_malloc(line_buffer_size, MALLOC_CAP_INTERNAL);

    if (line_buffer == NULL)
    {
        printf("[LCD ERROR] Brak pamieci na bufor linii w fillScreen!\n");
        return;
    }

    // 1. WYCIĄGAMY SKŁADOWE Z FORMATU RGB565
    uint16_t r = (color >> 11) & 0x1F; // 5 bitów czerwonego
    uint16_t g = (color >> 5) & 0x3F;  // 6 bitów zielonego
    uint16_t b = color & 0x1F;         // 5 bitów niebieskiego

    // 2. SKŁADAMY W FORMACIE BGR565 (Zamiana R i B miejscami)
    uint16_t bgr_color = (b << 11) | (g << 5) | r;

    // 3. OBRACAMY BAJTY DLA SYGNAŁU MIPI-DSI (Tak jak w poprzednim kroku)
    uint16_t fixed_color = __builtin_bswap16(bgr_color);

    for (uint16_t i = 0; i < width; i++)
    {
        line_buffer[i] = fixed_color;
    }

    // Rysujemy ekran linia po linii przez natywne DMA
    for (uint16_t y = 0; y < height; y++)
    {
        esp_lcd_panel_draw_bitmap(panel_handle, 0, y, width, y + 1, (uint8_t *)line_buffer);
    }

    free(line_buffer);
}

